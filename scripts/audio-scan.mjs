// Lists the sound files you have dropped into assets/audio/ so the game only loads files that exist.
// Usage: node scripts/audio-scan.mjs   (the build runs it for you)
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'audio');
await mkdir(dir, { recursive: true });
const files = (await readdir(dir)).filter((f) => /\.(mp3|ogg|wav|m4a)$/i.test(f)).sort();
await writeFile(path.join(dir, 'audio-list.js'), `// Generated by scripts/audio-scan.mjs. Do not edit by hand.\nwindow.EMBER_AUDIO = ${JSON.stringify(files)};\n`);
console.log(`audio: ${files.length} file(s) found in assets/audio`);
