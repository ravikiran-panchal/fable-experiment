// Cuts the site's sounds from CC0 packs with ffmpeg and writes assets/audio/SOURCES.md (the licensing record).
// Nothing is synthesized: every output is a trimmed, levelled copy of a recorded CC0 file.
//   node scripts/build-audio.mjs --src "<folder holding the downloaded packs>"
// Default --src is the sibling project's pack folder (../fable-experiment/assets/audio/_src).
// The finished mp3 files are committed, so this only needs re-running when a sound changes. Needs ffmpeg on PATH.
import { spawnSync } from 'node:child_process';
import { mkdir, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const i = process.argv.indexOf('--src');
const src = path.resolve(i > -1 ? process.argv[i + 1] : path.join(root, '..', 'fable-experiment', 'assets', 'audio', '_src'));
const out = path.join(root, 'assets', 'audio');
const CC0 = '[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/)';

const packs = {
  k_ui: { title: 'Interface Sounds', author: 'Kenney', site: 'Kenney.nl', page: 'https://kenney.nl/assets/interface-sounds' },
  swishes: { title: 'Swishes Sound Pack', author: 'artisticdude', site: 'OpenGameArt', page: 'https://opengameart.org/content/swishes-sound-pack' },
  magic1: { title: 'Magic Spell SFX', author: 'JaggedStone', site: 'OpenGameArt', page: 'https://opengameart.org/content/magic-spell-sfx' },
  rpg80: { title: '80 CC0 RPG SFX', author: 'rubberduck', site: 'OpenGameArt', page: 'https://opengameart.org/content/80-cc0-rpg-sfx' },
  sfx100: { title: '100 CC0 SFX', author: 'rubberduck', site: 'OpenGameArt', page: 'https://opengameart.org/content/100-cc0-sfx' },
  forest_amb: { title: 'Forest Ambience', author: 'TinyWorlds', site: 'OpenGameArt', page: 'https://opengameart.org/content/forest-ambience' },
};

// slot -> [pack, file inside the pack, where it plays, extra ffmpeg audio filter]
const slots = {
  ui_tick: ['k_ui', 'Audio/click_001.ogg', 'Buttons and library cards'],
  sign_ok: ['k_ui', 'Audio/confirmation_001.ogg', 'Each hand sign accepted'],
  cast: ['swishes', 'swishes/swish-7.wav', 'Sequence complete, jutsu starts'],
  release: ['swishes', 'swishes/swish-9.wav', 'Jutsu released'],
  sphere: ['magic1', 'magical_1_0.ogg', 'Spiral sphere forms'],
  lightning: ['k_ui', 'Audio/glitch_002.ogg', 'Lightning blade ignites (stand-in: no CC0 electric crackle on disk yet)'],
  eye: ['sfx100', 'gong_02.ogg', 'Eye awakening'],
  sand: ['rpg80', 'stones_03.ogg', 'Sand guardian rises (stand-in: stones, no CC0 sand sound on disk yet)'],
  fire: ['rpg80', 'spell_fire_03.ogg', 'Fire stream ignites'],
  valley_gong: ['sfx100', 'gong_01.ogg', 'Arriving in the bamboo valley'],
  valley_loop: ['forest_amb', 'Forest_Ambience.mp3', 'Bamboo valley ambience (loops)', 'volume=0.8'],
};

await mkdir(out, { recursive: true });
const rows = [];
for (const [slot, [pack, file, used, filter]] of Object.entries(slots)) {
  const input = path.join(src, pack, ...file.split('/'));
  await access(input).catch(() => { throw new Error(`Missing source file: ${input}`); });
  const args = ['-y', '-v', 'error', '-i', input, '-ac', '2', '-ar', '44100', '-af', filter || 'loudnorm=I=-16:TP=-1.5:LRA=11', '-b:a', '128k', path.join(out, `${slot}.mp3`)];
  const r = spawnSync('ffmpeg', args, { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`ffmpeg failed on ${slot} (is ffmpeg installed and on PATH?)`);
  const p = packs[pack];
  rows.push(`| \`${slot}.mp3\` | [${p.title} / ${file}](${p.page}) by ${p.author} | ${p.site} | ${CC0} | ${used} | None (public domain) |`);
  console.log('built', slot);
}
await writeFile(path.join(out, 'SOURCES.md'), `# Audio sources

Generated by \`scripts/build-audio.mjs\`. Every file is CC0 (public domain), converted to mp3 and levelled from the
source named here. Nothing is synthesized. No attribution is required; this table is the record of where each sound came from.

| File | Asset | Source | Licence | Where used | Your action |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`);
console.log('wrote assets/audio/SOURCES.md');
